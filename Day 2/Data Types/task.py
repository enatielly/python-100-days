# Subscripting - (ou indexação) é o ato de acessar um
# elemento específico dentro de uma sequência (como uma string, uma lista ou uma tupla)
# apontando para a posição exata dele.
# Os colchetes [] são o operador de subscripting.

print("Hello"[4])

print("Hello"[-1])

# Primitive data types
# String
print("123" + "123")

# Interger = Whole number
print(123 + 123)

# Large Intergers
print(123_456_789)

# Float = Floating Point Number
print(3.14159)

#Boolean
print(True)
print(False)
